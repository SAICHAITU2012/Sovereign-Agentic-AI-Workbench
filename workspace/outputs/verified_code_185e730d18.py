def add_numbers(a, b):
    # Print initial addition step
    print(f"Adding {a} and {b}")
    
    # Perform addition
    result = a + b
    
    # Print intermediate calculation step
    print(f"{a} + {b} equals {result}")
    
    # Print final result line
    print(f"The sum of {a} and {b} is {result}")

# Example usage:
add_numbers(5, 3)